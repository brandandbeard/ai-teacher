/**
 * Strict Bengali & English Bilingual Filter and Audio Hallucination Guard
 * 
 * Ensures student voice input and model outputs are strictly recognized as
 * Bengali (বাংলা), English, or mixed Bengali-English (Benglish code-switching).
 * Suppresses phantom acoustic hallucinations (Korean Hangul, French fillers,
 * Chinese Hanzi, Japanese Kana, Cyrillic, Arabic) caused by background noise.
 */

// Foreign non-Bengali, non-Latin scripts (Devanagari Hindi, Gurmukhi, Gujarati, Odia, Tamil, Telugu, Kannada, Malayalam, Sinhala, Korean Hangul, Chinese Hanzi, Japanese Kana, Cyrillic Russian, Arabic, Thai, Greek, Hebrew)
// Note: Bengali script (\u0980-\u09FF) and Basic Latin / ASCII are strictly preserved.
export const FOREIGN_SCRIPTS_REGEX =
  /[\u0900-\u097F\u0A00-\u0D7F\u0D80-\u0DFF\u0F00-\u109F\u1100-\u11FF\u1780-\u17FF\u3040-\u30FF\u3130-\u318F\u3400-\u4DBF\u4E00-\u9FFF\uAC00-\uD7A3\u0400-\u04FF\u0590-\u05FF\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\u0E00-\u0E7F\u0370-\u03FF]/g;

// Set of common French and German acoustic hallucination tokens often generated by Gemini from ambient mic noise
const FOREIGN_HALLUCINATION_TOKENS = new Set([
  // French
  'oui', 'merci', 'beaucoup', 'daccord', 'bonjour', 'salut', 'au', 'revoir',
  'voila', 'tres', 'bien', 'cest', 'ca', 'je', 'suis', 'de', 'rien',
  'enchante', 'pourquoi', 'comment', 'sil', 'vous', 'plait', 'bonne', 'nuit',
  'monsieur', 'madame', 'alors', 'avec',
  // German acoustic hallucinations (e.g. "Blihartzahnarzt", "Ja. Da haben Sie")
  'zahnarzt', 'blihartzahnarzt', 'zahnarzte', 'haben', 'sie', 'sind', 'nicht',
  'nichts', 'wiedersehen', 'guten', 'morgen', 'danke', 'bitte', 'deutsch',
  'deutschland', 'doch', 'alles', 'klar', 'richtig', 'genau', 'sehr', 'warum',
  'heute', 'gestern', 'ja', 'nein', 'da', 'wir', 'ihr', 'und', 'ist', 'das', 'der',
  'die', 'herr', 'frau', 'ein', 'eine', 'einen', 'einem', 'einer', 'mit', 'nach',
  'von', 'zu', 'bei', 'auch', 'aber', 'oder', 'wenn', 'als', 'wie'
]);

function isAllForeignHallucinationTokens(str: string): boolean {
  const normalized = str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // strip accents (e.g. ä, ö, ü, é)
    .replace(/['’]/g, '') // remove apostrophes: d'accord -> daccord, c'est -> cest
    .replace(/[^a-z\s]/g, ' ')
    .trim();

  if (!normalized) return false;
  // If the string contains specific acoustic nonsense like "blihartzahnarzt"
  if (normalized.includes('blihartzahnarzt') || normalized.includes('zahnarzt')) {
    return true;
  }
  const words = normalized.split(/\s+/).filter(Boolean);
  if (words.length === 0) return false;
  return words.every((w) => FOREIGN_HALLUCINATION_TOKENS.has(w));
}

/**
 * Sanitizes input text, ensuring only Bengali, English, or mixed Bengali-English content survives.
 * Discards pure foreign script noise or hallucinated French phrases.
 */
export function sanitizeBilingualText(text: string): string {
  if (!text || typeof text !== 'string') return '';

  const trimmed = text.trim();
  if (!trimmed) return '';

  // 1. Filter out pure French/German acoustic hallucinations
  if (isAllForeignHallucinationTokens(trimmed)) {
    return '';
  }

  // 2. Check and strip non-Bengali foreign scripts (Korean, Chinese, Japanese, etc.)
  if (FOREIGN_SCRIPTS_REGEX.test(trimmed)) {
    let stripped = trimmed.replace(FOREIGN_SCRIPTS_REGEX, '').trim();
    // Clean up any dangling leading/trailing punctuation/ellipses caused by removing foreign prefix (e.g. "어... text")
    stripped = stripped.replace(/^[\s.,…\-—~:;]+/, '').replace(/[\s.,…\-—~:;]+$/, '').trim();
    // If stripped text has no alphanumeric or Bengali characters left, discard it entirely
    if (!stripped || !/[a-zA-Z0-9\u0980-\u09FF]/.test(stripped)) {
      return '';
    }
    return stripped.replace(/\s{2,}/g, ' ');
  }

  return trimmed;
}

/**
 * Checks whether an incoming transcript is a foreign hallucination.
 */
export function isForeignHallucination(text: string): boolean {
  if (!text || typeof text !== 'string') return false;
  const trimmed = text.trim();
  if (isAllForeignHallucinationTokens(trimmed)) return true;
  if (FOREIGN_SCRIPTS_REGEX.test(trimmed)) {
    const stripped = trimmed.replace(FOREIGN_SCRIPTS_REGEX, '').trim();
    if (!stripped || !/[a-zA-Z0-9\u0980-\u09FF]/.test(stripped)) {
      return true;
    }
  }
  return false;
}
